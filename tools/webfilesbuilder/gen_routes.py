"""Auto-generate static asset routes from webh/ gzip headers.

Called as a PlatformIO pre-extra script (via exec()), so __file__ is not
available. Falls back to os.getcwd() which is the project root at build time.
"""

import os
from datetime import datetime

PROJECT_ROOT = os.getcwd()
WEBH_DIR = os.path.join(PROJECT_ROOT, 'src', 'webh')
OUTPUT_FILE = os.path.join(PROJECT_ROOT, 'src', 'web_routes.h')


def derive_symbol(filename):
    name = filename[:-2]
    return name.replace('.', '_').replace('-', '_')


def derive_original_filename(filename):
    if filename.endswith('.gz.h'):
        return filename[:-5]
    return filename


def get_route_info(orig_filename):
    ext = os.path.splitext(orig_filename)[1].lower()
    if ext == '.js':
        return f"/js/{orig_filename}", "contTypeTextJs"
    elif ext == '.css':
        return f"/css/{orig_filename}", "contTypeTextCss"
    elif ext == '.svg':
        return f"/{orig_filename}", '"image/svg+xml"'
    elif ext == '.png':
        return f"/{orig_filename}", '"image/png"'
    elif ext == '.ico':
        return f"/{orig_filename}", '"img/png"'
    return None, None


def main():
    os.makedirs(WEBH_DIR, exist_ok=True)
    files = sorted(os.listdir(WEBH_DIR))
    gz_h_files = [f for f in files if f.endswith('.gz.h')]

    includes = []
    routes = []
    now = datetime.now().strftime('%Y-%m-%d %H:%M:%S')

    for f in gz_h_files:
        if f.endswith('.html.gz.h'):
            continue
        if 'i18next' in f:
            continue
        orig = derive_original_filename(f)
        url, mime = get_route_info(orig)
        if url is None:
            continue
        sym = derive_symbol(f)
        sym_len = sym + '_len'
        includes.append(f'#include "webh/{f}"')
        routes.append((url, mime, sym, sym_len))

    content = '// Auto-generated by gen_routes.py - DO NOT EDIT\n'
    content += f'// Generated: {now}\n\n'
    for inc in includes:
        content += inc + '\n'
    content += ('\nstruct StaticRoute {\n'
                '    const char *url;\n'
                '    const char *mime;\n'
                '    const uint8_t *data;\n'
                '    unsigned len;\n'
                '};\n\n'
                'static const StaticRoute kStaticRoutes[] = {\n')
    for url, mime, sym, sym_len in routes:
        content += f'    {{"{url}", {mime}, {sym}, {sym_len}}},\n'
    content += ('};\n\n'
                'inline void registerStaticRoutes() {\n'
                '    for (const auto &r : kStaticRoutes) {\n'
                '        serverWeb.on(r.url, [r]() { sendGzip(r.mime, r.data, r.len); });\n'
                '    }\n'
                '}\n')

    with open(OUTPUT_FILE, 'w') as f:
        f.write(content)
    print(f"Generated {OUTPUT_FILE} with {len(routes)} routes ({len(gz_h_files)} .gz.h files scanned, {len([f for f in gz_h_files if f.endswith('.html.gz.h')])} HTML skipped)")


main()
